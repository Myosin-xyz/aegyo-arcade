import { ProductionCutoverRefusal } from "./production-cutover-lib.mjs";

export function productionCutoverConfig(bundle, env, phase) {
  const a = bundle.liveAttestation;
  const required = (name) =>
    env[name] ||
    (() => {
      throw new ProductionCutoverRefusal(`missing_${name}`);
    })();
  return {
    phase,
    attestationPhase: a.phase,
    attestationCapturedAt: a.capturedAt,
    confirm: env.ACCOUNTS_PRODUCTION_CUTOVER_CONFIRM,
    projectId: a.projectId,
    environmentId: a.environmentId,
    operatorServiceId: env.RAILWAY_SERVICE_ID,
    attestedOperatorServiceId: a.operatorServiceId,
    sourceDatabaseServiceId: a.sourceDatabaseServiceId,
    accountsServiceId: a.accountsServiceId,
    accountsDatabaseServiceId: a.accountsDatabaseServiceId,
    sourceDatabase: a.sourceDatabase,
    accountsDatabase: a.accountsDatabase,
    accountsRuntimeRole: env.ACCOUNTS_DATABASE_ROLE,
    accountsBaseURL: a.accountsBaseURL,
    aegyoBaseURL: a.aegyoBaseURL,
    sourceNamespace: a.sourceNamespace,
    aegyoDeploymentId: a.aegyoDeploymentId,
    aegyoRevision: a.aegyoRevision,
    reviewedAegyoRevision: bundle.reviewedAegyoRevision,
    requiredFreezeAncestor: bundle.requiredFreezeAncestor,
    reviewedRevisionIncludesFreeze: bundle.reviewedRevisionIncludesFreeze,
    aegyoBuildCommand: a.aegyoBuildCommand,
    aegyoStartCommand: a.aegyoStartCommand,
    aegyoPredeployCommand: a.aegyoPredeployCommand,
    accountsDeploymentId: a.accountsDeploymentId,
    accountsImageDigest: a.accountsImageDigest,
    environment: a.accountsEnvironment,
    accountsTrafficEnabled: a.accountsTrafficEnabled,
    accountsSignupEnabled: a.accountsSignupEnabled,
    aegyoFreezeEnabled: a.aegyoFreezeEnabled,
    aegyoSharedAuthEnabled: a.aegyoSharedAuthEnabled,
    aegyoRequestsDrained: a.aegyoRequestsDrained,
    directWritersPaused: a.directWritersPaused,
    attestedAegyoServiceId: a.aegyoServiceId,
    attestedAegyoDeploymentId: a.aegyoDeploymentId,
    attestedAegyoRevision: a.aegyoRevision,
    attestedAccountsServiceId: a.accountsServiceId,
    attestedAccountsDeploymentId: a.accountsDeploymentId,
    attestedAccountsImageDigest: a.accountsImageDigest,
    attestedFreezeEnabled: a.aegyoFreezeEnabled,
    attestedSharedAuthEnabled: a.aegyoSharedAuthEnabled,
    attestedAccountsTrafficEnabled: a.accountsTrafficEnabled,
    attestedAccountsSignupEnabled: a.accountsSignupEnabled,
    attestedSourceDatabaseHost: a.sourceDatabaseHost,
    attestedAccountsDatabaseHost: a.accountsDatabaseHost,
    ordinaryDatabaseUrl: env.DATABASE_URL,
    runId: required("ACCOUNTS_PRODUCTION_CUTOVER_RUN_ID"),
    sourceReadOnlyRole: required("AEGYO_CUTOVER_READ_ONLY_ROLE"),
    sourceOwnerRole: required("AEGYO_CUTOVER_OWNER_ROLE"),
    accountsOwnerRole: required("ACCOUNTS_CUTOVER_OWNER_ROLE"),
    expectedUsers: Number(required("ACCOUNTS_IMPORT_EXPECTED_COUNT")),
    expectedSourceTables: 51,
    sourceSchemaStatus: "additive-v1",
    sourceReaderUrl: required("AEGYO_CUTOVER_READER_DATABASE_URL"),
    sourceOwnerUrl: required("AEGYO_CUTOVER_OWNER_DATABASE_URL"),
    accountsOwnerUrl: required("ACCOUNTS_CUTOVER_OWNER_DATABASE_URL"),
    approvedSnapshotDigest: env.ACCOUNTS_IMPORT_APPROVED_DIGEST,
    approvedPreservationDigest: env.AEGYO_APPROVED_PRESERVATION_DIGEST,
    approvedMappingDigest: env.AEGYO_MAPPING_APPROVED_DIGEST,
    recoveryProviderIdDigest: a.recoveryProviderIdDigest,
    recoveryEvidence: a.recoveryEvidence,
  };
}
